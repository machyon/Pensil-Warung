-- ---------------------------------------------------------------------
-- users (one account = one warung)
-- ---------------------------------------------------------------------
CREATE TABLE users (
  id            uuid        PRIMARY KEY DEFAULT uuidv7(),   -- time-ordered
  email         text        NOT NULL,
  display_name  text        NOT NULL,   -- "Nama" on Daftar; blank -> 'user <n>' (trigger)
  username      text        NOT NULL,   -- shown in Settings; NULL on insert -> generated; editable
  role_id       integer     NOT NULL DEFAULT 1 REFERENCES roles (id),   -- 1 = user (seeded)
  -- Theme and text size are handled by the application, not stored here.
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT users_display_name_chars CHECK (display_name ~ '^[A-Za-z0-9 ]+$'),
  CONSTRAINT users_display_name_trim  CHECK (display_name = btrim(display_name)),
  CONSTRAINT users_display_name_len   CHECK (char_length(display_name) BETWEEN 1 AND 50),
  CONSTRAINT users_username_format    CHECK (username ~ '^[a-z0-9_]{3,30}$'),
  CONSTRAINT users_email_lower        CHECK (email = lower(email))
);
CREATE UNIQUE INDEX users_email_key    ON users (email);
CREATE UNIQUE INDEX users_username_key ON users (username);
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Used for the fallback name "user 1", "user 2", ... when a name has nothing usable in it.
CREATE SEQUENCE user_number_seq;

-- Picks a free username from a display name.
--   "Siti Rahayu" -> siti_rahayu
--   if that is already used: count the usernames that look like siti_rahayu or
--   siti_rahayu_<number>, and use siti_rahayu_<count>.
-- Counting alone can land on a name that is taken (for example after one account
-- was deleted or renamed), so the loop keeps counting up until the name is free.
-- Two signups at the exact same moment can still pick the same name: the unique
-- index rejects the second one (SQLSTATE 23505), and the app retries the insert.
CREATE FUNCTION generate_username(display_name text) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  base      text := left(slugify_username(display_name), 24);   -- leaves room for _<count>
  n         integer;
  candidate text;
BEGIN
  IF char_length(base) < 3 THEN
    base := 'user_' || base;                                    -- usernames need 3+ characters
  END IF;

  SELECT count(*) INTO n
    FROM users
   WHERE username ~ ('^' || base || '(_[0-9]+)?$');

  candidate := CASE WHEN n = 0 THEN base ELSE base || '_' || n END;

  WHILE EXISTS (SELECT 1 FROM users WHERE username = candidate) LOOP
    n := n + 1;
    candidate := base || '_' || n;
  END LOOP;

  RETURN candidate;
END $$;

-- Runs before every insert, and whenever display_name is updated. It fills in
-- blanks only. It does NOT clean or parse a name: sanitizing belongs to the
-- backend and the UI.
--   1. If display_name is NULL or blank, use "user <number>" from user_number_seq.
--   2. On insert, if no username was given, generate one.
-- A name that is present but has anything other than letters, digits and spaces
-- ("José", "Siti!") is left alone and rejected by users_display_name_chars with an
-- error, as are names with leading or trailing spaces or over 50 characters.
-- The fallback uses a space, not an underscore, because display names only allow
-- letters, digits and spaces. Its username comes out as user_<number>.
CREATE FUNCTION users_before_write() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.display_name IS NULL OR btrim(NEW.display_name) = '' THEN
    NEW.display_name := 'user ' || nextval('user_number_seq');
  END IF;

  IF TG_OP = 'INSERT' AND NEW.username IS NULL THEN
    NEW.username := generate_username(NEW.display_name);
  END IF;

  RETURN NEW;
END $$;
CREATE TRIGGER users_before_write BEFORE INSERT OR UPDATE OF display_name ON users
  FOR EACH ROW EXECUTE FUNCTION users_before_write();

-- ---------------------------------------------------------------------
-- auth_identities: how a user can log in (Google and/or email+password)
-- Google is verified directly with Google's official credentials (no managed
-- auth service), so identities live here.
-- ---------------------------------------------------------------------
CREATE TABLE auth_identities (
  id               bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id          uuid          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  provider         auth_provider NOT NULL,
  provider_user_id text,          -- Google "sub"; NULL for password
  password_hash    text,          -- argon2/bcrypt hash; NULL for google
  created_at       timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT auth_identity_shape CHECK (
    (provider = 'google'   AND provider_user_id IS NOT NULL AND password_hash IS NULL) OR
    (provider = 'password' AND password_hash    IS NOT NULL AND provider_user_id IS NULL)
  ),
  CONSTRAINT auth_one_per_provider UNIQUE (user_id, provider)
);
CREATE UNIQUE INDEX auth_google_sub_key ON auth_identities (provider_user_id)
  WHERE provider = 'google';

-- ---------------------------------------------------------------------
-- products (Produk)
-- ---------------------------------------------------------------------
CREATE TABLE products (
  id         bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id    uuid          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name       text          NOT NULL,
  price      bigint        NOT NULL,                 -- rupiah, current price
  stock      numeric(12,3) NOT NULL DEFAULT 0,       -- derived from stock_movements
  photo_key  text,                                   -- Tigris object key; optional ("Foto boleh nanti")
  created_at timestamptz   NOT NULL DEFAULT now(),
  updated_at timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT products_name_not_blank CHECK (btrim(name) <> ''),
  CONSTRAINT products_price_nonneg   CHECK (price >= 0),
  -- This is what rejects a sale when stock is not enough.
  CONSTRAINT products_stock_nonneg   CHECK (stock >= 0)
);
-- The typed-command parser matches names case-insensitively per warung.
CREATE UNIQUE INDEX products_user_name_key ON products (user_id, lower(btrim(name)));
CREATE TRIGGER products_updated_at BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------
-- transactions (one "Simpan" on Catat = one transaction, many items)
-- Transactions are never deleted. A mistake is voided.
-- ---------------------------------------------------------------------
CREATE TABLE transactions (
  id          bigint             GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id     uuid               NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  client_uuid uuid,                                  -- made by the phone; retry-safe (offline later)
  raw_text    text               NOT NULL,           -- exactly what the user typed
  total       bigint             NOT NULL,           -- sum of item line_totals
  status      transaction_status NOT NULL DEFAULT 'completed',
  occurred_at timestamptz        NOT NULL DEFAULT now(),   -- when the sale happened
  created_at  timestamptz        NOT NULL DEFAULT now(),   -- when the server stored it
  voided_at   timestamptz,
  void_reason text,

  CONSTRAINT transactions_total_nonneg CHECK (total >= 0),
  CONSTRAINT transactions_void_shape   CHECK ((status = 'voided') = (voided_at IS NOT NULL)),
  CONSTRAINT transactions_client_uuid_key UNIQUE (user_id, client_uuid)   -- NULLs allowed, many
);
CREATE INDEX transactions_user_time_idx ON transactions (user_id, occurred_at DESC);

-- ---------------------------------------------------------------------
-- transaction_items: a snapshot of what was sold, at the price at the time
-- product_id is SET NULL on product delete, so history survives.
-- ---------------------------------------------------------------------
CREATE TABLE transaction_items (
  id             bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  transaction_id bigint        NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
  product_id     bigint        REFERENCES products (id) ON DELETE SET NULL,
  line_no        smallint      NOT NULL,             -- order of the line in raw_text
  product_name   text          NOT NULL,             -- snapshot
  unit_price     bigint        NOT NULL,             -- snapshot
  quantity       numeric(12,3) NOT NULL,
  line_total     bigint        NOT NULL,

  CONSTRAINT items_quantity_pos  CHECK (quantity > 0),
  CONSTRAINT items_price_nonneg  CHECK (unit_price >= 0),
  CONSTRAINT items_line_total_ok CHECK (line_total = round(quantity * unit_price)),
  CONSTRAINT items_line_unique   UNIQUE (transaction_id, line_no)
);
CREATE INDEX items_product_idx ON transaction_items (product_id) WHERE product_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- stock_movements: ledger of every stock change
-- delta > 0 adds stock (initial, restock, void_sale), delta < 0 removes it
-- (sale, or a negative adjustment). stock_after is filled by the trigger.
-- ---------------------------------------------------------------------
CREATE TABLE stock_movements (
  id                  bigint        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id          bigint        NOT NULL REFERENCES products (id) ON DELETE CASCADE,
  transaction_item_id bigint        REFERENCES transaction_items (id) ON DELETE SET NULL,
  reason              stock_reason  NOT NULL,
  delta               numeric(12,3) NOT NULL,
  stock_after         numeric(12,3) NOT NULL,
  note                text,
  created_at          timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT movements_delta_nonzero CHECK (delta <> 0)
);
CREATE INDEX movements_product_time_idx ON stock_movements (product_id, created_at DESC);

-- Apply the delta to products.stock under a row lock, then record the result.
-- If stock would go below 0, the products_stock_nonneg check fails and the
-- whole sale is rolled back (SQLSTATE 23514).
CREATE FUNCTION apply_stock_movement() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE products
     SET stock = stock + NEW.delta
   WHERE id = NEW.product_id
   RETURNING stock INTO NEW.stock_after;
  RETURN NEW;
END $$;
CREATE TRIGGER stock_movements_apply BEFORE INSERT ON stock_movements
  FOR EACH ROW EXECUTE FUNCTION apply_stock_movement();

-- A product created with stock 20 gets an 'initial' ledger row automatically.
CREATE FUNCTION product_initial_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.stock <> 0 THEN
    UPDATE products SET stock = 0 WHERE id = NEW.id;
    INSERT INTO stock_movements (product_id, reason, delta, stock_after)
    VALUES (NEW.id, 'initial', NEW.stock, 0);   -- stock_after is overwritten by the trigger
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER products_initial_stock AFTER INSERT ON products
  FOR EACH ROW EXECUTE FUNCTION product_initial_stock();

-- Selling an item takes stock out.
CREATE FUNCTION item_sale_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.product_id IS NOT NULL THEN
    INSERT INTO stock_movements (product_id, transaction_item_id, reason, delta, stock_after)
    VALUES (NEW.product_id, NEW.id, 'sale', -NEW.quantity, 0);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER items_sale_stock AFTER INSERT ON transaction_items
  FOR EACH ROW EXECUTE FUNCTION item_sale_stock();

-- Voiding a transaction puts the stock back (only for items whose product still exists).
CREATE FUNCTION transaction_void_stock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'completed' AND NEW.status = 'voided' THEN
    INSERT INTO stock_movements (product_id, transaction_item_id, reason, delta, stock_after)
    SELECT i.product_id, i.id, 'void_sale', i.quantity, 0
      FROM transaction_items i
     WHERE i.transaction_id = NEW.id AND i.product_id IS NOT NULL;
  ELSIF OLD.status = 'voided' AND NEW.status = 'completed' THEN
    RAISE EXCEPTION 'A voided transaction cannot be restored';
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER transactions_void_stock AFTER UPDATE OF status ON transactions
  FOR EACH ROW EXECUTE FUNCTION transaction_void_stock();

-- ---------------------------------------------------------------------
-- broadcasts (Siaran). Sent to all users; no per-user state.
-- App feed: WHERE status = 'sent' ORDER BY broadcasted_at DESC, id DESC LIMIT 5
-- ---------------------------------------------------------------------
CREATE TABLE broadcasts (
  id             integer            GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  category       broadcast_category NOT NULL,
  title          varchar(60)        NOT NULL,
  summary        varchar(120)       NOT NULL,        -- shown in the notification list
  body           text,                               -- optional full text
  status         broadcast_status   NOT NULL DEFAULT 'scheduled',
  scheduled_for  timestamptz,                        -- set when scheduled
  broadcasted_at timestamptz,                        -- the sent time; NULL until sent
  created_by     uuid               REFERENCES users (id) ON DELETE SET NULL,
  created_at     timestamptz        NOT NULL DEFAULT now(),
  cancelled_by   uuid               REFERENCES users (id) ON DELETE SET NULL,
  cancelled_at   timestamptz,

  CONSTRAINT broadcasts_title_not_blank   CHECK (btrim(title) <> ''),
  CONSTRAINT broadcasts_summary_not_blank CHECK (btrim(summary) <> ''),
  CONSTRAINT broadcasts_status_shape CHECK (
    (status = 'scheduled' AND scheduled_for  IS NOT NULL AND broadcasted_at IS NULL     AND cancelled_at IS NULL) OR
    (status = 'sent'      AND broadcasted_at IS NOT NULL AND cancelled_at   IS NULL) OR
    (status = 'cancelled' AND cancelled_at   IS NOT NULL AND broadcasted_at IS NULL)
  )
);
CREATE INDEX broadcasts_feed_idx ON broadcasts (broadcasted_at DESC, id DESC)
  WHERE status = 'sent';
CREATE INDEX broadcasts_due_idx ON broadcasts (scheduled_for)
  WHERE status = 'scheduled';

-- ---------------------------------------------------------------------
-- Daily totals for History / Analytics (day boundary = Asia/Jakarta)
-- ---------------------------------------------------------------------
CREATE VIEW v_daily_sales AS
SELECT t.user_id,
       (t.occurred_at AT TIME ZONE 'Asia/Jakarta')::date AS day,
       count(*)                                          AS transaction_count,
       sum(t.total)                                      AS revenue
  FROM transactions t
 WHERE t.status = 'completed'
 GROUP BY t.user_id, (t.occurred_at AT TIME ZONE 'Asia/Jakarta')::date;
