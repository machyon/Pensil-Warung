-- =====================================================================
-- Pensil Warung: PostgreSQL 18 schema (v1)
-- Source: Hi-Fi page of the "Pensil Warung Onboarding" canvas.
--
-- Requires PostgreSQL 18 or newer (uuidv7()). Applied by refinery
-- (`backend migrate`), which runs it once, in a single transaction, and
-- records it in refinery_schema_history. Never edit it once applied.
--
-- Conventions
--   * Money is whole rupiah, stored as bigint (never float).
--   * Quantities and stock are numeric(12,3). The UI is whole numbers for
--     now; decimals are allowed in the database for later.
--   * Every point in time is timestamptz (stored as UTC). "Day" grouping
--     in History/Analytics is done in Asia/Jakarta, see v_daily_sales.
--   * users.id is uuid (version 7). Everything else is an integer identity key.
--   * products.stock is only ever changed by inserting a stock_movements
--     row (a trigger applies it). Never UPDATE products.stock directly.
-- =====================================================================

