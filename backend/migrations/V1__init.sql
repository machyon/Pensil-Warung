CREATE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- "Siti Rahayu" -> "siti_rahayu". Display names only contain A-Z, 0-9 and
-- spaces (enforced on users), so this is lowercase + spaces to underscores.
-- Clash handling is in generate_username(), further down.
CREATE FUNCTION slugify_username(display_name text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT lower(regexp_replace(btrim(display_name), '\s+', '_', 'g'));
$$;

-- ---------------------------------------------------------------------
