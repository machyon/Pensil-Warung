CREATE TYPE transaction_status AS ENUM ('completed', 'voided');
CREATE TYPE stock_reason       AS ENUM ('initial', 'sale', 'void_sale', 'restock', 'adjustment');
CREATE TYPE broadcast_category AS ENUM ('update', 'berita', 'info', 'tips');   -- Pembaruan, Berita, Info, Tips
CREATE TYPE broadcast_status   AS ENUM ('scheduled', 'sent', 'cancelled');

